import numpy as np

# ----------------------------------------------------
# 1단계: 학습 데이터셋 정의 (국어, 수학, 영어, 과학)
# ----------------------------------------------------
X = np.array([
    [70, 100, 70, 80],
    [90, 60, 80, 80],
    [90, 90, 90, 100],
    [85, 70, 95, 75],
    [100, 55, 85, 90],
    [60, 95, 65, 70],
    [85, 85, 75, 85],
    [70, 90, 70, 75],
    [95, 65, 85, 75],
    [80, 75, 70, 70],
    [90, 85, 90, 95],
    [85, 70, 75, 70]
], dtype=float)

# 정답 레이블 (1: 합격, 0: 불합격)
y = np.array([1, 0, 1, 0, 0, 1, 1, 1, 0, 0, 1, 0], dtype=int)

# ----------------------------------------------------
# 2단계: 하이퍼파라미터 및 초기 파라미터 설정
# ----------------------------------------------------
w = np.array([0.1, 0.2, 0.3, 0.1], dtype=float)  # 초기 과목별 가중치
b = -20.0                                        # 초기 편향
eta = 0.005                                      # 학습률 (Learning Rate)
epochs = 50                                      # 학습 반복 횟수

# ----------------------------------------------------
# 3단계: 퍼셉트론 학습 루프 (SGD 방식 갱신)
# ----------------------------------------------------
print(f"{'Epoch':^7} | {'Accuracy':^12} | {'Weights (w1, w2, w3, w4)':^32} | {'Bias (b)':^8}")
print("-" * 68)

for epoch in range(1, epochs + 1):
    # 1) 현재 파라미터 기준 전체 데이터 분류 정확도 측정 (행렬 연산)
    pred_all = ((X @ w + b) >= 0).astype(int)
    correct_count = np.sum(pred_all == y)

    if epoch % 5 == 0 or epoch == 1:
        w_str = f"[{w[0]:.3f}, {w[1]:.3f}, {w[2]:.3f}, {w[3]:.3f}]"
        print(f"Epoch {epoch:2d} | {correct_count:2d}/{len(X)} ({correct_count/len(X)*100:5.1f}%) | {w_str} | {b:8.3f}")

    # 모든 샘플을 정확히 맞춘 경우 학습 조기 종료 (Zero Error)
    if correct_count == len(X):
        print("-" * 68)
        print(f"조기 종료 달성: Epoch {epoch}에서 100% 분류 정확도(12/12) 수렴 완료")
        break

    # 2) 샘플별 순차 탐색 및 오차 기반 파라미터 갱신
    for i in range(len(X)):
        # 순입력 가중합 계산
        net = np.dot(X[i], w) + b

        # 계단 활성화 함수 (Hard Limit Step)
        pred = 1 if net >= 0 else 0

        # 오차 산출
        err = y[i] - pred

        # 오차가 존재할 경우에만 퍼셉트론 갱신 규칙 적용
        if err != 0:
            w += eta * err * X[i]
            b += eta * err * 1.0

# ----------------------------------------------------
# 4단계: 최종 학습 결과 출력
# ----------------------------------------------------
print("-" * 68)
print("[최종 학습 완료 파라미터]")
print(f"최종 가중치: 국어={w[0]:.4f}, 수학={w[1]:.4f}, 영어={w[2]:.4f}, 과학={w[3]:.4f}")
print(f"최종 편향 (Bias): {b:.4f}")